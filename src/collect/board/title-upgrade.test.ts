import { describe, expect, it } from "vitest";
import { upgradeTruncatedTitle } from "./title-upgrade";

describe("잘린 목록 제목 승격(2026-09-05 안양)", () => {
  it("말줄임으로 끝나고 상세가 그 앞부분으로 시작하면 상세 제목을 준다", () => {
    expect(
      upgradeTruncatedTitle(
        "2026년 안양시 유망기업 온‧오프라...",
        "2026년 안양시 유망기업 온‧오프라인 유통망 입점 지원사업",
      ),
    ).toBe("2026년 안양시 유망기업 온‧오프라인 유통망 입점 지원사업");
  });

  it("공백 개수만 다른 자리도 승격한다 — 상세는 두 칸인 자리가 있다(실측)", () => {
    // 상세 원문: 「온‧오프라인  유통망」(두 칸). 정규화해 한 칸으로 돌려준다.
    expect(
      upgradeTruncatedTitle(
        "2026년 안양시 유망기업 온‧오프라...",
        "2026년 안양시 유망기업 온‧오프라인  유통망 입점 지원사업",
      ),
    ).toBe("2026년 안양시 유망기업 온‧오프라인 유통망 입점 지원사업");
  });

  it("말줄임이 없는 온전한 목록 제목은 상세가 접두어만 달라도 건드리지 않는다", () => {
    // 「제목이 실제로 바뀐 공고」를 옛 제목으로 되돌리지 않기 위한 방어.
    expect(
      upgradeTruncatedTitle(
        "2026 만안구 · 비산동 소공인 사업화 지원",
        "2026 만안구 · 비산동 소공인 사업화 지원사업 참여기업 모집",
      ),
    ).toBeNull();
  });

  it("목록과 상세가 같은 제목이면 null", () => {
    expect(upgradeTruncatedTitle("2026년 수출보험 지원", "2026년 수출보험 지원")).toBeNull();
  });

  it("선택자가 틀려 무관한 글자를 집어 오면 null — 잘린 제목보다 나쁜 덮어쓰기를 막는다", () => {
    expect(
      upgradeTruncatedTitle("2026년 안양시 유망기업 온‧오프라...", "안양산업진흥원 | 사업신청"),
    ).toBeNull();
  });

  /**
   * ★무관한 제목이 **잘린 앞부분보다 길 때**도 막아야 한다.
   * 위 시험은 상세가 짧아서 길이 검사만으로도 걸린다 — 접두어 검사를 지워도 통과했다
   * (2026-09-05 돌연변이 검증에서 드러난 구멍). 페이지 제목·안내문은 대개 길다.
   */
  it("무관한 글자가 잘린 앞부분보다 길어도 null — 접두어 검사가 실제로 일한다", () => {
    expect(
      upgradeTruncatedTitle(
        "2026년 안양시 유망기업 온‧오프라...",
        "안양산업진흥원 사업신청 안내 — 기업지원사업 통합 공고 목록 페이지입니다",
      ),
    ).toBeNull();
  });

  it("상세가 잘린 앞부분보다 짧으면 null", () => {
    expect(
      upgradeTruncatedTitle("2026년 안양시 유망기업 온‧오프라...", "2026년 안양시"),
    ).toBeNull();
  });

  /**
   * ★같으면(정규화 후 글자까지 동일)도 승격한다(2026-09-06 안양 sbIdx=535 실측) — 원래 제목이
   * 20자 안에 다 들어갔는데 출처가 그래도 말줄임을 붙인 경우다. 「더 길어야 한다」로 두면
   * null 로 떨어져 말줄임이 영영 안 떼어지고 dedupKey 가 임시 열쇠로 남는다.
   */
  it("상세가 잘린 앞부분과 길이까지 같으면 말줄임만 뗀 제목을 승격한다", () => {
    expect(
      upgradeTruncatedTitle("2026년 중소기업 수출보험 지원...", "2026년 중소기업 수출보험 지원"),
    ).toBe("2026년 중소기업 수출보험 지원");
  });

  it("상세 제목이 비었으면(선택자 0건) null", () => {
    expect(upgradeTruncatedTitle("2026년 안양시 유망기업 온‧오프라...", "")).toBeNull();
    expect(upgradeTruncatedTitle("2026년 안양시 유망기업 온‧오프라...", "   ")).toBeNull();
  });

  it("말줄임만 있고 앞부분이 비면 null", () => {
    expect(upgradeTruncatedTitle("...", "2026년 안양시 유망기업 지원사업")).toBeNull();
  });

  it("`…`(한 글자 말줄임)·`..`(두 점)도 같은 규칙으로 승격한다", () => {
    expect(upgradeTruncatedTitle("2026년 수출보험…", "2026년 수출보험 지원사업")).toBe(
      "2026년 수출보험 지원사업",
    );
    expect(upgradeTruncatedTitle("2026년 수출보험..", "2026년 수출보험 지원사업")).toBe(
      "2026년 수출보험 지원사업",
    );
  });

  it("목록 제목이 비었으면 null", () => {
    expect(upgradeTruncatedTitle("", "2026년 안양시 유망기업 지원사업")).toBeNull();
  });
});
