import { describe, expect, it } from "vitest";
import { deadlineFromTitle } from "./title-deadline";

// 실제 게시판 제목 표기 그대로(독립 검사 4차 실측 — 27건이 모집중에 남던 형식들).
describe("deadlineFromTitle — 제목 속 마감 표기를 종료일로", () => {
  it("두 자리 연도 점 형식 「~26.8.28」", () => {
    expect(deadlineFromTitle("지원사업 공고(~26.8.28)", "2026-08-10")).toBe("2026-08-28");
  });
  it("연도 없는 점 형식 「~3.27.,17:00」 — 등록 연도로 완성", () => {
    expect(deadlineFromTitle("사업재편 지원사업 기업모집 연장 공고(~3.27.,17:00)", "2026-03-17")).toBe("2026-03-27");
  });
  it("연도 없는 점 형식 「~8.17(월)」", () => {
    expect(deadlineFromTitle("체외진단의료기기 On-Site Meeting 신청 안내(~8.17(월))", "2026-08-10")).toBe("2026-08-17");
  });
  it("끝점 붙는 「~8.25.」", () => {
    expect(deadlineFromTitle("참여기관(업) 모집 공고(~8.25.(화) 18:00)", "2026-08-05")).toBe("2026-08-25");
  });
  it("빗금 형식 「~8/24 13시까지」", () => {
    expect(deadlineFromTitle("수행기업 모집 통합 연장 공고(~8/24 13시까지)", "2026-08-18")).toBe("2026-08-24");
  });
  it("한글 형식 「~8월 28일(금) 18:00까지」", () => {
    expect(deadlineFromTitle("참여기관 모집(~8월 28일(금) 18:00까지)", "2026-08-13")).toBe("2026-08-28");
  });
  it("물결 없는 「6월 23일(화) 18시까지」 — 까지 앵커", () => {
    expect(deadlineFromTitle("모집공고(6월 23일(화) 18시까지)", "2026-06-10")).toBe("2026-06-23");
  });
  it("연말 걸침 「~1/15」 — 등록 12월이면 이듬해", () => {
    expect(deadlineFromTitle("모집 공고(~1/15)", "2026-12-20")).toBe("2027-01-15");
  });
  it("마감 표기 없으면 빈 문자열", () => {
    expect(deadlineFromTitle("2026년 스마트공장 구축 지원사업 공고", "2026-08-01")).toBe("");
  });
  it("「2025~2026년」 같은 연도 범위를 마감으로 오인하지 않는다", () => {
    expect(deadlineFromTitle("2025~2026년 지원사업 안내", "2026-08-01")).toBe("");
  });
  it("「30~50억」 같은 숫자 범위를 오인하지 않는다", () => {
    expect(deadlineFromTitle("매출 30~50억 기업 모집", "2026-08-01")).toBe("");
  });
  it("까지 없는 날짜(개최일)는 마감으로 안 잡는다", () => {
    expect(deadlineFromTitle("설명회 개최(6월 23일)", "2026-06-10")).toBe("");
  });
  it("앞의 시작일을 건너뛰고 까지 붙은 날짜를 잡는다", () => {
    expect(deadlineFromTitle("9월 30일부터 신청, 10월 15일까지", "2026-09-01")).toBe("2026-10-15");
  });
  it("등록일이 없으면 연도 있는 형식만 잡는다", () => {
    expect(deadlineFromTitle("공고(~26.8.28)", "")).toBe("2026-08-28");
    expect(deadlineFromTitle("공고(~8.17)", "")).toBe("");
  });
});

// 독립 검사 5차: 금액·비율 표기를 날짜로 읽으면 살아 있는 공고가 즉시 마감된다.
describe("deadlineFromTitle — 돈·비율은 날짜가 아니다", () => {
  it("「최대 ~1.5억원 지원」을 날짜로 읽지 않는다", () => {
    expect(deadlineFromTitle("최대 ~1.5억원 지원 사업 공고", "2026-08-01")).toBe("");
  });
  it("「금리 ~2.5% 지원」을 날짜로 읽지 않는다", () => {
    expect(deadlineFromTitle("소상공인 자금(금리 ~2.5% 지원) 안내", "2026-08-01")).toBe("");
  });
  it("「지원한도 3.5억원까지」를 날짜로 읽지 않는다", () => {
    expect(deadlineFromTitle("지원한도 3.5억원까지 모집", "2026-08-01")).toBe("");
  });
  it("「1인당 1.2천만원까지 지원」을 날짜로 읽지 않는다", () => {
    expect(deadlineFromTitle("교육비 1인당 1.2천만원까지 지원", "2026-08-01")).toBe("");
  });
  it("「~50억 규모」처럼 단위가 붙어도 안 읽는다", () => {
    expect(deadlineFromTitle("총 ~50억 규모 지원사업", "2026-08-01")).toBe("");
  });
  it("돈 표기가 섞여 있어도 진짜 마감은 잡는다", () => {
    expect(deadlineFromTitle("최대 1.5억원 지원사업 모집(~9.30)", "2026-08-01")).toBe("2026-09-30");
  });
  it("추출한 마감이 등록일보다 앞서면 버린다(과거 날짜로 즉시 마감되는 사고 방지)", () => {
    expect(deadlineFromTitle("지원한도 3.5억원까지 모집", "2026-03-01")).toBe("");
  });
});
