export const WEDLY_CATEGORIES = ["인증제도", "R&D·기술", "수출", "고용·인력", "정책자금", "무상지원금", "기타"] as const;
export type WedlyCategory = (typeof WEDLY_CATEGORIES)[number];

/**
 * 추천 화면에 보여 줄 **순서** — 돈을 받는 사업이 앞이다(사장님 2026-08-30
 * 「무상지원금·정책자금·인건비 지원처럼 돈 받는 정책이 최우선, 그 외는 뒤로」).
 * 분류 자체(WEDLY_CATEGORIES)는 저장 값이라 순서를 바꾸지 않고, 보여 주는 차례만 여기서 정한다.
 */
export const RECOMMEND_CATEGORY_ORDER: readonly WedlyCategory[] = [
  "무상지원금",   // 갚지 않는 돈
  "정책자금",     // 융자·이차보전
  "고용·인력",   // 인건비 지원
  "R&D·기술",    // 사업비 지원
  "수출",
  "인증제도",     // 돈이 아니라 자격
  "기타",
];

const RULES: Array<{ re: RegExp; cat: WedlyCategory }> = [
  { re: /인증|벤처.{0,6}확인|이노비즈|메인비즈|기업부설연구소|연구소\s*(설립|인정)|지정\s*신청/, cat: "인증제도" },
  { re: /R&D|연구개발|기술개발|과제\s*(기획|공고|모집)|실증|테스트베드/i, cat: "R&D·기술" },
  { re: /수출|해외|무역|글로벌\s*진출|전시회|바이어|국제\s*박람회/, cat: "수출" },
  { re: /고용|채용|일자리|훈련|장려금|인건비|근로환경|직업능력/, cat: "고용·인력" },
  { re: /융자|대출|보증(?!금)|이차보전|자금\s*(지원|공고|계획)|정책자금|육성자금/, cat: "정책자금" },
  { re: /지원\s*사업|지원금|바우처|환급|사업화|마케팅|컨설팅|기술보급|창업패키지|창업보육|입주\s*기업|스마트공장/, cat: "무상지원금" },
  // ↑ 2026-08-29 운영 4,717건 백필 후 「기타」 표본 30건 눈검증으로 보강(설계 §3 약속·적대 리뷰 지적):
  //   「디지털 전환지원 사업」(띄어쓰기)·「컨설팅 사업」·「창업보육센터 입주기업」·「스마트공장 구축」이 기타로 새고 있었다.
  //   요금 감면·복지·농업 제도류는 기업 지원이 아니라 기타가 맞다 — 억지로 줄이지 않는다.
];

/** 자금 낱말 — 이게 있으면 R&D·수출 어휘가 섞여 있어도 자금 성격이다(적대 리뷰: 「기술개발자금 융자」). */
const FUND_RE = /융자|대출|이차보전|보증(?!금)|육성자금|정책자금/;
/** 고용 낱말 — 「해외취업」이 수출로 새지 않게 수출보다 먼저 본다(적대 리뷰 반례). */
const HR_RE = /취업|채용|일자리|고용|훈련|장려금|인건비|근로환경|직업능력/;

export function classifyWedlyCategory(title: string, summary: string): WedlyCategory {
  const text = `${title} ${summary}`;
  // 1단계 — 설계서 §3 이 스스로 못 박은 우선순위: 「기술개발자금 융자」는 R&D 가 아니라 자금 성격.
  if (FUND_RE.test(text)) return "정책자금";
  // 2단계 — 「청년 해외취업 연수」류가 「해외」 낱말로 수출에 먹히지 않게.
  if (HR_RE.test(text)) return "고용·인력";
  for (const { re, cat } of RULES) if (re.test(text)) return cat;
  return "기타";
}
